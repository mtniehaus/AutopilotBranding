<#
.SYNOPSIS
Checks an .intunewin generated by the web builder against one made by SvRooij.ContentPrep (New-AutopilotBrandingPackage).

.DESCRIPTION
1. Decodes the reference package (made by SvRooij.ContentPrep) with this script's reading of the .intunewin format
   (HMAC-SHA256 | IV | AES-256-CBC, keys in Detection.xml).  If that works, the format assumptions the web builder is
   built on match the real tool.
2. Decodes the web package the same way and checks that its Detection.xml has the same structure.
3. Compares the web package's content with the reference output folder (generated from the same configuration):
   same files, same bytes, and an equivalent AutopilotBranding.json.
4. Runs the self-contained check and, when elevated, the web package's runner script (which exits because OOBE has
   already completed).
5. If the SvRooij.ContentPrep module can decrypt packages (Unlock-IntuneWinPackage), decrypts the web package with it.
Exits with code 1 if a check fails.

.PARAMETER WebPackage
The .intunewin generated by the web builder (e.g. with web\dist-node\generate.mjs).

.PARAMETER ReferencePackage
An .intunewin made by New-AutopilotBrandingPackage from the same configuration.

.PARAMETER ReferenceOutput
The output folder New-AutopilotBrandingPackage packaged into ReferencePackage.
#>
[CmdletBinding()]
param (
	[Parameter(Mandatory = $true)] [string] $WebPackage,
	[Parameter(Mandatory = $true)] [string] $ReferencePackage,
	[Parameter(Mandatory = $true)] [string] $ReferenceOutput
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
$repoRoot = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
Import-Module (Join-Path $repoRoot 'Module\AutopilotBranding\AutopilotBranding.psd1') -Force
$temp = Join-Path ([System.IO.Path]::GetTempPath()) ('ABWeb-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -Path $temp -ItemType Directory -Force | Out-Null
$failures = New-Object System.Collections.Generic.List[string]

function Check([string] $Name, [scriptblock] $Test) {
	try {
		& $Test
		Write-Host "[PASS] $Name" -ForegroundColor Green
	}
	catch {
		$failures.Add($Name)
		Write-Host "[FAIL] $Name`n       $($_.Exception.Message)" -ForegroundColor Red
	}
}

function Read-ZipEntry([System.IO.Compression.ZipArchive] $Zip, [string] $Name) {
	$entry = $Zip.Entries | Where-Object { $_.FullName -eq $Name } | Select-Object -First 1
	if (-not $entry) { throw "Entry $Name not found" }
	$stream = $entry.Open()
	try {
		$memory = New-Object System.IO.MemoryStream
		$stream.CopyTo($memory)
		return , $memory.ToArray()
	}
	finally {
		$stream.Dispose()
	}
}

function Compare-Bytes([byte[]] $A, [byte[]] $B) {
	if ($A.Length -ne $B.Length) { return $false }
	for ($i = 0; $i -lt $A.Length; $i++) { if ($A[$i] -ne $B[$i]) { return $false } }
	return $true
}

function Expand-ABIntuneWin([string] $Path, [string] $Destination) {
	# Decodes an .intunewin and extracts its content; returns the Detection.xml document
	$zip = [System.IO.Compression.ZipFile]::OpenRead((Resolve-Path $Path).Path)
	try {
		$names = @($zip.Entries | ForEach-Object { $_.FullName } | Sort-Object)
		$expected = @('IntuneWinPackage/Contents/IntunePackage.intunewin', 'IntuneWinPackage/Metadata/Detection.xml')
		if (($names -join '|') -ne ($expected -join '|')) { throw "Unexpected entries: $($names -join ', ')" }
		$xmlBytes = Read-ZipEntry $zip 'IntuneWinPackage/Metadata/Detection.xml'
		$encrypted = Read-ZipEntry $zip 'IntuneWinPackage/Contents/IntunePackage.intunewin'
	}
	finally {
		$zip.Dispose()
	}
	[xml]$xml = [System.Text.Encoding]::UTF8.GetString($xmlBytes).TrimStart([char]0xFEFF)
	$info = $xml.ApplicationInfo.EncryptionInfo
	$key = [Convert]::FromBase64String($info.EncryptionKey)
	$macKey = [Convert]::FromBase64String($info.MacKey)
	$iv = [Convert]::FromBase64String($info.InitializationVector)
	$mac = [Convert]::FromBase64String($info.Mac)
	if ($key.Length -ne 32 -or $macKey.Length -ne 32 -or $iv.Length -ne 16) { throw 'Unexpected key or IV length' }

	$fileMac = New-Object byte[] 32
	[Array]::Copy($encrypted, 0, $fileMac, 0, 32)
	if (-not (Compare-Bytes $fileMac $mac)) { throw 'The first 32 bytes of the encrypted content are not the Mac in Detection.xml' }
	$fileIv = New-Object byte[] 16
	[Array]::Copy($encrypted, 32, $fileIv, 0, 16)
	if (-not (Compare-Bytes $fileIv $iv)) { throw 'Bytes 32-47 of the encrypted content are not the InitializationVector in Detection.xml' }
	$hmac = New-Object System.Security.Cryptography.HMACSHA256 (, $macKey)
	$computed = $hmac.ComputeHash($encrypted, 32, $encrypted.Length - 32)
	if (-not (Compare-Bytes $computed $mac)) { throw 'HMAC-SHA256(IV | ciphertext) does not match the Mac' }

	$aes = [System.Security.Cryptography.Aes]::Create()
	$aes.Key = $key
	$aes.IV = $iv
	$aes.Mode = [System.Security.Cryptography.CipherMode]::CBC
	$aes.Padding = [System.Security.Cryptography.PaddingMode]::PKCS7
	$plain = $aes.CreateDecryptor().TransformFinalBlock($encrypted, 48, $encrypted.Length - 48)
	if ($plain.Length -ne [long]$xml.ApplicationInfo.UnencryptedContentSize) { throw "UnencryptedContentSize is $($xml.ApplicationInfo.UnencryptedContentSize), content is $($plain.Length) bytes" }
	$digest = [System.Security.Cryptography.SHA256]::Create().ComputeHash($plain)
	if ([Convert]::ToBase64String($digest) -ne $info.FileDigest) { throw 'FileDigest (SHA-256 of the content) does not match' }

	$contentZip = Join-Path $temp ([guid]::NewGuid().ToString('N') + '.zip')
	[System.IO.File]::WriteAllBytes($contentZip, $plain)
	[System.IO.Compression.ZipFile]::ExtractToDirectory($contentZip, $Destination)
	return $xml
}

function Get-Shape([xml] $Xml) {
	# Element names in document order, attributes of the root (values left out)
	$names = @($Xml.SelectNodes('//*') | ForEach-Object { $_.Name })
	$attributes = @($Xml.DocumentElement.Attributes | ForEach-Object { $_.Name } | Sort-Object)
	"$($names -join ',') | $($attributes -join ',')"
}

Write-Host "PowerShell $($PSVersionTable.PSVersion)"
$referenceDir = Join-Path $temp 'reference'
$webDir = Join-Path $temp 'web'
$referenceXml = $null
$webXml = $null

Check 'Reference package (SvRooij.ContentPrep) decodes with the web builder''s reading of the format' {
	$script:referenceXml = Expand-ABIntuneWin -Path $ReferencePackage -Destination $referenceDir
	Write-Host "       Reference Detection.xml shape: $(Get-Shape $script:referenceXml)"
	Write-Host "       ToolVersion $($script:referenceXml.ApplicationInfo.ToolVersion), Name $($script:referenceXml.ApplicationInfo.Name), SetupFile $($script:referenceXml.ApplicationInfo.SetupFile), FileName $($script:referenceXml.ApplicationInfo.FileName)"
}

Check 'Web package decodes (MAC, IV, AES, digest, size)' {
	$script:webXml = Expand-ABIntuneWin -Path $WebPackage -Destination $webDir
}

Check 'Detection.xml has the same structure and values as the reference (except keys and sizes)' {
	if (-not $referenceXml -or -not $webXml) { throw 'A package did not decode' }
	if ((Get-Shape $webXml) -ne (Get-Shape $referenceXml)) { throw "Shape differs:`n  web:       $(Get-Shape $webXml)`n  reference: $(Get-Shape $referenceXml)" }
	foreach ($name in 'Name', 'FileName', 'SetupFile') {
		if ($webXml.ApplicationInfo.$name -ne $referenceXml.ApplicationInfo.$name) { throw "$name differs: $($webXml.ApplicationInfo.$name) vs $($referenceXml.ApplicationInfo.$name)" }
	}
	foreach ($name in 'ProfileIdentifier', 'FileDigestAlgorithm') {
		if ($webXml.ApplicationInfo.EncryptionInfo.$name -ne $referenceXml.ApplicationInfo.EncryptionInfo.$name) { throw "$name differs" }
	}
}

Check 'The reference package contains the reference output folder' {
	$a = @(Get-ChildItem $referenceDir -Recurse -File | ForEach-Object { $_.FullName.Substring($referenceDir.Length + 1) } | Sort-Object)
	$b = @(Get-ChildItem $ReferenceOutput -Recurse -File | ForEach-Object { $_.FullName.Substring((Resolve-Path $ReferenceOutput).Path.Length + 1) } | Sort-Object)
	if (($a -join '|') -ne ($b -join '|')) { throw 'The reference package and output folder differ' }
}

Check 'Web package content matches the PowerShell output for the same configuration' {
	$referenceRoot = (Resolve-Path $ReferenceOutput).Path
	$a = @(Get-ChildItem $webDir -Recurse -File | ForEach-Object { $_.FullName.Substring($webDir.Length + 1) } | Sort-Object)
	$b = @(Get-ChildItem $referenceRoot -Recurse -File | ForEach-Object { $_.FullName.Substring($referenceRoot.Length + 1) } | Sort-Object)
	$onlyWeb = @($a | Where-Object { $b -notcontains $_ })
	$onlyReference = @($b | Where-Object { $a -notcontains $_ })
	if ($onlyWeb.Count -or $onlyReference.Count) { throw "Files differ.  Only in the web package: $($onlyWeb -join ', ').  Only in the PowerShell output: $($onlyReference -join ', ')" }
	foreach ($relative in $a | Where-Object { $_ -ne 'AutopilotBranding.json' }) {
		if ((Get-FileHash (Join-Path $webDir $relative)).Hash -ne (Get-FileHash (Join-Path $referenceRoot $relative)).Hash) { throw "$relative differs" }
	}
	$webConfig = ConvertTo-Json -InputObject (Read-ABConfiguration -Path (Join-Path $webDir 'AutopilotBranding.json')) -Depth 10 -Compress
	$referenceConfig = ConvertTo-Json -InputObject (Read-ABConfiguration -Path (Join-Path $referenceRoot 'AutopilotBranding.json')) -Depth 10 -Compress
	if ($webConfig -ne $referenceConfig) { throw "AutopilotBranding.json differs:`n  web:       $webConfig`n  reference: $referenceConfig" }
}

Check 'Web package is self-contained' {
	$problems = @(Test-ABOutputSelfContained -OutputPath $webDir)
	if ($problems.Count) { throw ($problems | ForEach-Object { $_.Message }) -join '; ' }
}

Check 'Web package runner script runs (log, OOBE check)' {
	$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
	if (-not $isAdmin) { Write-Host '       Skipped: requires elevation' -ForegroundColor Yellow; return }
	$output = & (Get-Process -Id $PID).Path -NoProfile -ExecutionPolicy Bypass -File (Join-Path $webDir 'AutopilotBranding.ps1') 2>&1 | Out-String
	if ($LASTEXITCODE -ne 0) { throw "Exit code $LASTEXITCODE`n$output" }
	$log = Get-Content "$($env:ProgramData)\Microsoft\AutopilotBranding\AutopilotBranding.log" -Raw
	if ($log -notmatch 'OOBE is completed') { throw "Unexpected log: $log" }
}

Check 'SvRooij.ContentPrep can decrypt the web package (if it has Unlock-IntuneWinPackage)' {
	Import-Module SvRooij.ContentPrep.Cmdlet -ErrorAction SilentlyContinue
	$unlock = Get-Command Unlock-IntuneWinPackage -ErrorAction SilentlyContinue
	if (-not $unlock) { Write-Host '       Skipped: Unlock-IntuneWinPackage is not available' -ForegroundColor Yellow; return }
	$parameters = @($unlock.Parameters.Keys)
	Write-Host "       Unlock-IntuneWinPackage parameters: $($parameters -join ', ')"
	$sourceName = @('SourceFile', 'Path', 'SourcePath', 'IntuneWinFile') | Where-Object { $parameters -contains $_ } | Select-Object -First 1
	$destinationName = @('DestinationPath', 'Destination', 'OutputPath', 'DestinationFolder') | Where-Object { $parameters -contains $_ } | Select-Object -First 1
	if (-not $sourceName -or -not $destinationName) { Write-Host '       Skipped: unrecognized parameters' -ForegroundColor Yellow; return }
	$unlockDir = Join-Path $temp 'unlocked'
	New-Item -Path $unlockDir -ItemType Directory -Force | Out-Null
	$arguments = @{ $sourceName = (Resolve-Path $WebPackage).Path; $destinationName = $unlockDir }
	Unlock-IntuneWinPackage @arguments | Out-Null
	$files = @(Get-ChildItem $unlockDir -Recurse -File)
	if ($files.Count -eq 0) { throw 'Unlock-IntuneWinPackage produced no files' }
	Write-Host "       Unlock-IntuneWinPackage extracted $($files.Count) file(s): $(($files | Select-Object -First 3 | ForEach-Object { $_.Name }) -join ', ')"
}

Remove-Item $temp -Recurse -Force -ErrorAction SilentlyContinue
if ($failures.Count) {
	Write-Host "Failed: $($failures -join ', ')" -ForegroundColor Red
	exit 1
}
Write-Host 'All web package checks passed'
exit 0
